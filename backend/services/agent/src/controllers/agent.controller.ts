import axios from "axios";
import { graph } from "../graph/graph.js";
import { Request, Response } from "express";

export const agent = async (req: Request, res: Response) => {
    try {
        const { prompt, conversationId } = req.body;

        if (!prompt) {
            return res.status(400).json({ message: "Prompt is required" });
        }

        const chatService = process.env.CHAT_SERVICE || "http://localhost:8002";

        // Save user message to chat history if conversationId is provided
        if (conversationId) {
            await axios.post(`${chatService}/save-message`, {
                conversationId,
                role: "user",
                content: prompt
            });
        }

        // Run the agent workflow
        const result = await graph.invoke({
            prompt,
            conversationId
        });

        const response = result.aiResponse || "No response generated by agent.";

        // Save assistant message to chat history if conversationId is provided
        if (conversationId) {
            await axios.post(`${chatService}/save-message`, {
                conversationId,
                role: "assistant",
                content: typeof response === "string" ? response : JSON.stringify(response)
            });
        }

        return res.status(200).json(response);
    } catch (error: any) {
        const errorMessage = error?.response?.data?.error || error?.message || String(error);
        return res.status(500).json({ message: `Agent error: ${errorMessage}` });
    }
};
